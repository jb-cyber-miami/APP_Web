def doable(item: CatalogExercise, equipment: frozenset[EquipmentKey]) -> bool:
    return item.requires <= frozenset(equipment)


@cache
def _index() -> dict[str, CatalogExercise]:
    return {normalize_name(item.name): item for item in CATALOG}


def find(name: str) -> CatalogExercise | None:
    """Catalog entry with the same normalized name, if any."""
    return _index().get(normalize_name(name))
