"""Built-in exercise catalog for the no-AI fallback plan and fallback swaps (AI_COACH section 8).

Names are standard, generic exercise names; the cues are written for FitLog. Every muscle
group has at least four entries and at least one that needs no equipment, so a brand-new user
with an empty library and a bodyweight-only gym still gets a sensible plan.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import cache

from .muscles import EquipmentKey, MuscleGroup, Pattern, normalize_name


@dataclass(frozen=True)
class CatalogExercise:
    name: str
    primary: MuscleGroup
    secondary: tuple[MuscleGroup, ...]
    pattern: Pattern
    requires: frozenset[EquipmentKey]  # all needed; empty = bodyweight
    compound: bool
    cues: tuple[str, ...]  # 2 short cues
    timed: bool = False  # holds and carries are prescribed in seconds


def _c(name, primary, secondary, pattern, requires, compound, cues, timed=False) -> CatalogExercise:
    return CatalogExercise(
        name, primary, tuple(secondary), pattern, frozenset(requires), compound, cues, timed
    )


